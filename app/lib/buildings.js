/** คืนชื่อเต็มของอาคาร (ถ้าไม่มี คืนสตริงว่าง) */
export function getBuildingName(code) {
  if (!code) return '';
  return BUILDING_NAMES[code] || '';
}

/** คืนป้ายกำกับสำหรับแสดงผล เช่น 'ท.0006 - อาคาร บริหารอะไหล่กังหันก๊าซ1' หากไม่มีชื่อเต็มจะคืน code เดิม */
export function getBuildingLabel(code) {
  if (!code) return '';
  const name = BUILDING_NAMES[code];
  return name ? `${code} - ${name}` : code;
}
